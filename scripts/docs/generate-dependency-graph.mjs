#!/usr/bin/env node
// Generates docs/dependency-graph.md: which frontend folders import which, drawn by dependency-cruiser.
// Usage: node scripts/docs/generate-dependency-graph.mjs [--check]
//   --check  exit 1 if docs/dependency-graph.md is out of date (used in CI)
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const OUTPUT = path.join(ROOT, 'docs', 'dependency-graph.md');
const CLI = path.join(ROOT, 'node_modules', 'dependency-cruiser', 'bin', 'dependency-cruiser.mjs');

// One box per top-level folder of frontend/src (app, api, components/<feature>, hooks, ...), so the graph
// stays readable as the code grows
const COLLAPSE = '^frontend/src/(components/[^/]+|app|[^/]+)';

const mermaid = execFileSync(
  process.execPath,
  [
    CLI,
    'frontend/src',
    '--config',
    '.dependency-cruiser.cjs',
    '--output-type',
    'mermaid',
    '--collapse',
    COLLAPSE,
  ],
  { cwd: ROOT, encoding: 'utf8' },
)
  .trim()
  // Same output on Windows and Linux
  .replaceAll('\r\n', '\n');

// Only draw once modules actually import each other; boxes without arrows explain nothing
const hasModules = mermaid.includes('-->');

const content = [
  '# Frontend dependency graph',
  '',
  '> Generated by `npm run docs:generate` (dependency-cruiser). Do not edit by hand.',
  '> One box per folder of `frontend/src` (one per feature under `components/`); an arrow means',
  '> "imports from". The same tool enforces the layer rules in `.dependency-cruiser.cjs`',
  '> (`npm run arch:check`). The backend keeps its own structure and is not drawn here.',
  '',
  ...(hasModules ? ['```mermaid', mermaid, '```'] : ['_No connections between folders yet._']),
  '',
].join('\n');

if (process.argv.includes('--check')) {
  // A Windows checkout may have CRLF line endings (.gitattributes text=auto): compare the text only
  const current = existsSync(OUTPUT) ? readFileSync(OUTPUT, 'utf8').replaceAll('\r\n', '\n') : '';
  if (current !== content) {
    process.stderr.write('docs/dependency-graph.md is out of date. Run: npm run docs:generate\n');
    process.exit(1);
  }
  process.exit(0);
}

writeFileSync(OUTPUT, content);
process.stdout.write('docs/dependency-graph.md updated\n');
